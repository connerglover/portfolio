"""Write fonts.css: every theme font as a base64 data URI.

Decks and documents load fonts.css, so a rendered HTML file carries its own
fonts and a printed PDF can never fall back to a system face. Run after adding
or replacing a file in fonts/:  python build_fonts.py
"""
import base64
from pathlib import Path

HERE = Path(__file__).parent
FONTS = HERE / 'fonts'

LATIN = 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+2000-206F, U+20AC, U+2122, U+2190-2193, U+2212, U+2215'
GREEK = 'U+0370-03FF'

# (family, file, weight, style, unicode-range)
FACES = [
    ('DE Display', 'archivo-var.woff2', '100 900', 'normal', None),
    ('DE Text', 'plex-sans-400.woff2', '400', 'normal', LATIN),
    ('DE Text', 'plex-sans-400-italic.woff2', '400', 'italic', LATIN),
    ('DE Text', 'plex-sans-500.woff2', '500', 'normal', LATIN),
    ('DE Text', 'plex-sans-600.woff2', '600', 'normal', LATIN),
    ('DE Text', 'plex-sans-greek-400.woff2', '400', 'normal', GREEK),
    ('DE Text', 'plex-sans-greek-500.woff2', '500', 'normal', GREEK),
    ('DE Text', 'plex-sans-greek-600.woff2', '600', 'normal', GREEK),
    ('DE Mono', 'plex-mono-400.woff2', '400', 'normal', LATIN),
    ('DE Mono', 'plex-mono-500.woff2', '500', 'normal', LATIN),
    # Formulas: MathML needs a font with an OpenType MATH table.
    ('DE Math', 'stix-two-math.woff2', '400', 'normal', None),
]


def main() -> None:
    out = ['/* Generated by build_fonts.py. Do not edit by hand. */']
    for family, name, weight, style, urange in FACES:
        data = base64.b64encode((FONTS / name).read_bytes()).decode('ascii')
        rules = [
            f"  font-family: '{family}';",
            f"  src: url(data:font/woff2;base64,{data}) format('woff2');",
            f'  font-weight: {weight};',
            f'  font-style: {style};',
            '  font-display: block;',
        ]
        if name.startswith('archivo'):
            rules.append('  font-stretch: 62% 125%;')
        if urange:
            rules.append(f'  unicode-range: {urange};')
        out.append('@font-face {\n' + '\n'.join(rules) + '\n}')
    (HERE / 'fonts.css').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'fonts.css: {len(FACES)} faces')


if __name__ == '__main__':
    main()
